export type Country = { code: string; name: Record<Lang, string> };
export const COUNTRIES: Country[] = ROWS.map(([code, fr, en, es]) => ({ code, name: { fr, en, es } }));
export const flagUrl = (code: string) => `https://flagcdn.com/w80/${code.toLowerCase()}.png`;

const norm = (s: string) => s.normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[’']/g, ' ').toLowerCase().trim();
/** Pays d'après son nom enregistré (français, ou une autre langue pour les saisies anciennes). */
export const countryByName = (name?: string | null) => {
  const n = norm(name || '');
  return n ? COUNTRIES.find(c => Object.values(c.name).some(x => norm(x) === n)) || null : null;
};
export const searchCountries = (q: string, lang: Lang) => {
  const n = norm(q);
  return n ? COUNTRIES.filter(c => norm(c.name[lang]).includes(n) || norm(c.name.fr).includes(n) || c.code.toLowerCase() === n) : COUNTRIES;
};
